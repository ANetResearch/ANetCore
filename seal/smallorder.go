package seal

import "crypto/ed25519"

// smallOrderY lists the y coordinates (little-endian, sign bit clear) of the eight Ed25519 points
// of small order: 1 (the identity, order 1), p - 1 (order 2), 0 (the two points of order 4), the
// two y coordinates of the four points of order 8, and the two non-canonical spellings p and
// p + 1 of 0 and 1. With the sign bit either way they are the 14 encodings a lenient decoder (Go's
// crypto/ed25519 among them) takes for a point of small order.
var smallOrderY = [...][ed25519.PublicKeySize]byte{
	{0x01},
	{0xec, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
		0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0x7f},
	{0x00},
	{0x26, 0xe8, 0x95, 0x8f, 0xc2, 0xb2, 0x27, 0xb0, 0x45, 0xc3, 0xf4, 0x89, 0xf2, 0xef, 0x98, 0xf0,
		0xd5, 0xdf, 0xac, 0x05, 0xd3, 0xc6, 0x33, 0x39, 0xb1, 0x38, 0x02, 0x88, 0x6d, 0x53, 0xfc, 0x05},
	{0xc7, 0x17, 0x6a, 0x70, 0x3d, 0x4d, 0xd8, 0x4f, 0xba, 0x3c, 0x0b, 0x76, 0x0d, 0x10, 0x67, 0x0f,
		0x2a, 0x20, 0x53, 0xfa, 0x2c, 0x39, 0xcc, 0xc6, 0x4e, 0xc7, 0xfd, 0x77, 0x92, 0xac, 0x03, 0x7a},
	{0xed, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
		0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0x7f},
	{0xee, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
		0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0x7f},
}

// smallOrder reports whether pub is an encoding of an Ed25519 point of small order (core
// CORE-K8a), canonical or not. Under such a key anyone can make a signature that verifies for a
// message of their choosing with a chance of about 1 in 8 (1 in 1 for the identity), so a
// mailbox key or a capability holder key must never be one. A key made from a seed, as every
// honest one is, never is: its scalar is a multiple of 8 in [2^254, 2^255), which is never a
// multiple of the (odd, prime) group order, so the key is a point of that prime order.
//
// The test is a fixed list (the libsodium check, with the sign bit ignored), not a point
// multiplication: it needs no decoding of the point and gives the same answer.
func smallOrder(pub []byte) bool {
	if len(pub) != ed25519.PublicKeySize {
		return false
	}
	for i := range smallOrderY {
		y := &smallOrderY[i]
		diff := pub[ed25519.PublicKeySize-1]&0x7f ^ y[ed25519.PublicKeySize-1]
		for j := 0; j < ed25519.PublicKeySize-1; j++ {
			diff |= pub[j] ^ y[j]
		}
		if diff == 0 {
			return true
		}
	}
	return false
}
